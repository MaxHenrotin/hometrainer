"""Writes js/drawings.js: the GPS drawings made from pictures and real data rather than drawn by hand.
Adding or removing one is a line in LINES or LEVELS at the bottom, then running this script again."""
import json
from pathlib import Path

import numpy as np
from fontTools.pens.basePen import BasePen
from fontTools.svgLib.path import parse_path
from PIL import Image
from shapely import LineString

import terrain
import tsp

HERE = Path(__file__).parent
# Drawings with levels of detail: a ride follows the richest one its length draws cleanly at one GPS point
# a second. These are the shortest rides (km) for each level, and what each level holds.
LEVEL_KM = [0, 12, 25]
DOTS = [300, 700, 1400]  # TSP dots
RIDGES = [(14, 70), (24, 100), (40, 140)]  # ridgelines, and points along each
MATTERHORN = (45.9763, 7.6586)


def normal(line, tolerance=0.6):
    """The line in integers, its longest side 1000 long, without the points a straight line passes within
    `tolerance` of."""
    line = np.asarray(line, float)
    line = (line - line.min(0)) * 1000 / np.ptp(line, axis=0).max()
    return np.rint(LineString(line).simplify(tolerance, preserve_topology=False).coords).astype(int).tolist()


class Line(BasePen):
    """The points of an SVG path, its curves cut into short segments."""
    def __init__(self):
        super().__init__(None)
        self.points = []

    def _moveTo(self, p): self.points.append(p)
    def _lineTo(self, p): self.points.append(p)
    def _qCurveToOne(self, p1, p2): self._curveToOne(p1, p1, p2)
    def _curveToOne(self, p1, p2, p3):
        p0 = np.array(self.points[-1])
        t = np.linspace(0, 1, 7)[1:, None]
        self.points += list((1 - t) ** 3 * p0 + 3 * (1 - t) ** 2 * t * p1 + 3 * (1 - t) * t ** 2 * p2 + t ** 3 * p3)
    def _closePath(self): self.points.append(self.points[0])


def zap():
    """Lucide's zap icon (ISC, see lucide-LICENSE)."""
    pen = Line()
    parse_path(open(HERE / "zap.svg").read().split(' d="')[1].split('"')[0], pen)
    return np.array(pen.points) * [1, -1]


def beat(x, width, height):
    """One heartbeat starting at x: the P, Q, R, S and T waves as Gaussians (McSharry et al. 2003)."""
    t = np.linspace(0, 1, 160)
    waves = [(0.2, 0.12, 0.025), (0.335, -0.1, 0.008), (0.36, 1, 0.01), (0.385, -0.22, 0.009), (0.62, 0.28, 0.045)]
    return np.stack([x + t * width, height * sum(h * np.exp(-((t - c) / w) ** 2 / 2) for c, h, w in waves)], 1)


def llama(dots):
    """The 'Llama del Perú' engraving (Museo Nacional de Ciencias Naturales, Madrid, public domain), without
    its stand and caption."""
    img = Image.open(HERE / "llama.jpg").convert("L").crop((0, 0, 606, 578))
    img = np.pad(np.clip((np.asarray(img, float) / 255 - 0.12) / 0.78, 0, 1), 30, constant_values=1)
    img = Image.fromarray((img * 255).astype(np.uint8)).resize((400, 400 * img.shape[0] // img.shape[1]), Image.LANCZOS)
    return tsp.drawing(np.asarray(img, float) / 255, dots)


# The climbs' roads from OpenStreetMap: the Overpass filter and the box they lie in
ROADS = {
    "alpeDHuez": ('["highway"]["ref"~"D ?211"]', (45.04, 6.02, 45.10, 6.08)),
    "stelvio": ('["highway"]["ref"~"SS ?38"]', (46.52, 10.44, 46.64, 10.60)),
    "tremola": ('["highway"]["name"~"Tremola"]', (46.52, 8.55, 46.57, 8.60)),
}


def roads():
    """Each climb's road as [lat, lon], fetched once and kept in roads.json."""
    path = HERE / "roads.json"
    kept = json.loads(path.read_text()) if path.exists() else {}
    for name, (query, bbox) in ROADS.items():
        if name not in kept:
            kept[name] = [[round(lat, 5), round(lon, 5)] for lat, lon in terrain.road(query, bbox)]
    path.write_text(json.dumps(kept, separators=(",", ":")))
    return kept


def stelvio_top(road, km=4):
    """The last `km` before the Stelvio pass coming up from Trafoi, where the bends stack up."""
    east, north = terrain.metres(46.53)
    road = np.array(road)
    top = int(np.argmin(np.hypot((road[:, 0] - 46.5287) * north, (road[:, 1] - 10.4533) * east)))
    side = road[:top + 1] if road[0, 1] > road[-1, 1] else road[top:][::-1]
    along = np.concatenate([[0], np.cumsum(np.hypot(np.diff(side[:, 0]) * north, np.diff(side[:, 1]) * east))])
    return side[along >= along[-1] - km * 1000]


def write(lines, levels):
    js = lambda value: json.dumps(value, separators=(",", ":"))
    out = "// Generated by assets/drawings/build.py, don't edit by hand. Each line is [x, y] points, y going up.\n"
    out += "// A drawing in LEVELS has one line per level of detail, simplest first, for rides of LEVEL_KM km and more.\n"
    out += f"export const LEVEL_KM = {js(LEVEL_KM)};\n"
    out += f"export const LINES = {js({name: normal(line) for name, line in lines.items()})};\n"
    out += f"export const LEVELS = {js({name: [normal(line) for line in each] for name, each in levels.items()})};\n"
    path = HERE.parents[1] / "js" / "drawings.js"
    path.write_text(out)
    print(path, f"{len(out) / 1000:.0f} kB")


road = roads()
write(lines={
    "zap": zap(),
    "ecg": np.vstack([beat(k, 1, 0.55) for k in range(3)]),
    "alpeDHuez": terrain.oblique(road["alpeDHuez"], 0, 50),
    "stelvio": terrain.oblique(stelvio_top(road["stelvio"]), 90, 55),
    "stelvioBends": terrain.oblique(stelvio_top(road["stelvio"]), 315, 55),
    "tremola": terrain.oblique(road["tremola"], 0, 50),
    "matterhornContours": terrain.contours(*MATTERHORN, 2500, range(3000, 4400, 100)),
}, levels={
    "litHeart": [tsp.drawing(tsp.heart(), n) for n in DOTS],
    "llama": [llama(n) for n in DOTS],
    "matterhorn": [terrain.ridgelines(*MATTERHORN, 240, 3000, -3000, 2500, lines, samples) for lines, samples in RIDGES],
})
