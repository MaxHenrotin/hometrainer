"""The outlines of the TT, the icon and the wordmark as one continuous line each, for the GPS drawings in js/route.js."""
import re

from fontTools.pens.basePen import BasePen
from fontTools.svgLib.path import parse_path
from shapely import Point, Polygon, box, make_valid, symmetric_difference_all, union_all


class Rings(BasePen):
    """Collects each subpath as a list of points. The rounded corners are a few units wide, too small for a map."""
    def __init__(self):
        super().__init__(None)
        self.rings = []

    def _moveTo(self, p): self.rings.append([p])
    def _lineTo(self, p): self.rings[-1].append(p)
    def _qCurveToOne(self, p1, p2): self._lineTo(p2)
    def _curveToOne(self, p1, p2, p3): self._lineTo(p3)
    def _closePath(self): pass


def disc(circle):
    """A <circle> as a disc, or as a ring when it is only stroked (the icon's tyre)."""
    a = dict(re.findall(r'(\S+)="([^"]*)"', circle))
    centre, r = Point(float(a["cx"]), 100 - float(a["cy"])), float(a["r"])
    if a["fill"] != "none":
        return centre.buffer(r)
    w = float(a["stroke-width"]) / 2
    return centre.buffer(r + w).difference(centre.buffer(r - w))


def shape(svg):
    """Union of the SVG's paths and circles, y up from the baseline, cut to the cap height like the viewBox does.
    Inside a path, overlapping subpaths cut holes (the counters)."""
    paths = []
    for d in (part.split('"')[0] for part in svg.split(' d="')[1:]):
        pen = Rings()
        parse_path(d, pen)
        paths.append(symmetric_difference_all([make_valid(Polygon([(x, 100 - y) for x, y in ring])) for ring in pen.rings]))
    paths += [disc(circle.split("/>")[0]) for circle in svg.split("<circle ")[1:]]
    return union_all(paths).intersection(box(-1e3, 0, 1e4, 100)).simplify(0.3)


def bottom(ring, side):
    """Index of the bottom-left (side=-1) or bottom-right (side=1) point of a ring."""
    low = min(y for _, y in ring)
    return max((side * x, i) for i, (x, y) in enumerate(ring) if y < low + 1)[1]


def nearest(ring, hole):
    return min((abs(complex(*ring[i]) - complex(*hole[j])), i, j) for i in range(len(ring)) for j in range(len(hole)))[1:]


def stroke(svg):
    """One line through every outline, left to right. Each letter starts at its bottom-left corner, holes are
    reached from the nearest point and back, and the line goes on to the next letter from the bottom-right corner."""
    polygons = sorted(getattr(shape(svg), "geoms", [shape(svg)]), key=lambda p: p.bounds[0])
    line = []
    for k, polygon in enumerate(polygons):
        ring = polygon.exterior.coords[:-1]
        start = bottom(ring, -1)
        ring = ring[start:] + ring[:start]
        detours = {}
        for hole in polygon.interiors:
            hole = hole.coords[:-1]
            i, j = nearest(ring, hole)
            detours.setdefault(i, []).extend(hole[j:] + hole[:j] + [hole[j], ring[i]])
        line += [p for i, point in enumerate(ring) for p in [point] + detours.get(i, [])] + [ring[0]]
        if k < len(polygons) - 1:
            end = bottom(ring, 1)
            forward, backward = ring[1:end + 1], ring[end:][::-1]
            length = lambda points: sum(abs(complex(*a) - complex(*b)) for a, b in zip([ring[0]] + points, points))
            line += min(forward, backward, key=length)
    return line


def js(drawings):
    """ES module exporting each line as [x, y] pairs."""
    out = "// Generated by assets/logo/build.py from the logo SVGs, don't edit by hand.\n"
    out += "// One continuous line around each outline, in the units of its SVG (a height of 100), y going up.\n"
    for name, line in drawings.items():
        out += f"export const {name} = [{', '.join(f'[{x:.1f}, {y:.1f}]' for x, y in line)}];\n"
    return out
